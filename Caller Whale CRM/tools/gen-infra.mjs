// Writes the Kubernetes files for every deployable part from tools/infra.json into infra/k8s/ (Kustomize: one folder
// per part, and one kustomization.yaml for everything). The output is committed; run this after changing the table.
//   node tools/gen-infra.mjs
//   node tools/gen-infra.mjs --check     fail if the files on disk are not what the table produces
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const labels = (name, indent) =>
  [`app.kubernetes.io/name: ${name}`, "app.kubernetes.io/part-of: callerwhale"].map(line => " ".repeat(indent) + line).join("\n");

/** Whether the part scales by itself: several copies allowed. */
const scales = s => s.replicas.max > s.replicas.min;

export function deployment(s) {
  const secret = s.secret
    ? `        envFrom:
          - secretRef:
              name: ${s.secret}${s.secretOptional ? "\n              optional: true" : ""}
`
    : "";
  const env = s.env
    ? `        env:
${Object.entries(s.env).map(([k, v]) => `          - { name: ${k}, value: "${v}" }`).join("\n")}
`
    : "";
  const mounts = [];
  const volumes = [];
  if (s.volume) {
    mounts.push(`          - { name: ${s.volume.name}, mountPath: ${s.volume.mount} }`);
    volumes.push(`        - name: ${s.volume.name}\n          persistentVolumeClaim:\n            claimName: ${s.name}-${s.volume.name}`);
  }
  if (s.readOnlyRoot) {
    mounts.push("          - { name: tmp, mountPath: /tmp }");
    volumes.push("        - name: tmp\n          emptyDir: {}");
  }
  const startup = s.startup
    ? `        startupProbe:
          httpGet: { path: /healthz, port: http }
          periodSeconds: 5
          failureThreshold: 36   # up to 3 minutes: it migrates its database when it starts
`
    : "";
  return `# Generated by tools/gen-infra.mjs from tools/infra.json. Do not edit by hand.
apiVersion: apps/v1
kind: Deployment
metadata:
  name: ${s.name}
  labels:
${labels(s.name, 4)}
spec:
${scales(s) ? "" : `  replicas: ${s.replicas.min}\n`}  revisionHistoryLimit: 3
  strategy:
${s.volume && s.volume.mode === "ReadWriteOnce" ? "    type: Recreate" : "    type: RollingUpdate\n    rollingUpdate: { maxSurge: 1, maxUnavailable: 0 }"}
  selector:
    matchLabels:
      app.kubernetes.io/name: ${s.name}
  template:
    metadata:
      labels:
${labels(s.name, 8)}
    spec:
      terminationGracePeriodSeconds: 30
      securityContext:
        runAsNonRoot: true
        runAsUser: ${s.uid}
        runAsGroup: ${s.uid}
        fsGroup: ${s.uid}
        seccompProfile: { type: RuntimeDefault }
      # Copies spread over different machines (and zones when there are several), so one machine going down
      # does not take every copy with it.
      topologySpreadConstraints:
        - maxSkew: 1
          topologyKey: kubernetes.io/hostname
          whenUnsatisfiable: ScheduleAnyway
          labelSelector:
            matchLabels:
              app.kubernetes.io/name: ${s.name}
        - maxSkew: 1
          topologyKey: topology.kubernetes.io/zone
          whenUnsatisfiable: ScheduleAnyway
          labelSelector:
            matchLabels:
              app.kubernetes.io/name: ${s.name}
      containers:
      - name: ${s.name}
        image: ${s.image}
        ports:
          - { name: http, containerPort: ${s.port} }
${secret}${env}        readinessProbe:
          httpGet: { path: /healthz, port: http }
          periodSeconds: 5
          failureThreshold: 3
        livenessProbe:
          httpGet: { path: /healthz, port: http }
          initialDelaySeconds: 10
          periodSeconds: 10
          failureThreshold: 3
${startup}        resources:
          requests: { cpu: ${s.cpu[0]}, memory: ${s.memory[0]} }
          limits: { cpu: "${s.cpu[1]}", memory: ${s.memory[1]} }
        securityContext:
          allowPrivilegeEscalation: false
          capabilities: { drop: [ALL] }${s.readOnlyRoot ? "\n          readOnlyRootFilesystem: true" : ""}
${mounts.length ? `        volumeMounts:\n${mounts.join("\n")}\n` : ""}${volumes.length ? `      volumes:\n${volumes.join("\n")}\n` : ""}`;
}

export function service(s) {
  return `# Generated by tools/gen-infra.mjs from tools/infra.json. Do not edit by hand.
apiVersion: v1
kind: Service
metadata:
  name: ${s.name}
  labels:
${labels(s.name, 4)}
spec:
  selector:
    app.kubernetes.io/name: ${s.name}
  ports:
    - { name: http, port: ${s.port}, targetPort: http }
`;
}

export function hpa(s) {
  return `# Generated by tools/gen-infra.mjs from tools/infra.json. Do not edit by hand.
apiVersion: autoscaling/v2
kind: HorizontalPodAutoscaler
metadata:
  name: ${s.name}
spec:
  scaleTargetRef: { apiVersion: apps/v1, kind: Deployment, name: ${s.name} }
  minReplicas: ${s.replicas.min}
  maxReplicas: ${s.replicas.max}
  metrics:
    - type: Resource
      resource:
        name: cpu
        target: { type: Utilization, averageUtilization: 70 }
  behavior:
    scaleDown:
      stabilizationWindowSeconds: 300   # wait five minutes of low load before removing copies
`;
}

export function pdb(s) {
  return `# Generated by tools/gen-infra.mjs from tools/infra.json. Do not edit by hand.
apiVersion: policy/v1
kind: PodDisruptionBudget
metadata:
  name: ${s.name}
spec:
  minAvailable: 1   # a node drain never takes the last copy
  selector:
    matchLabels:
      app.kubernetes.io/name: ${s.name}
`;
}

export function pvc(s) {
  return `# Generated by tools/gen-infra.mjs from tools/infra.json. Do not edit by hand.
# ${s.volume.note}
apiVersion: v1
kind: PersistentVolumeClaim
metadata:
  name: ${s.name}-${s.volume.name}
spec:
  accessModes: [${s.volume.mode}]
  resources:
    requests:
      storage: ${s.volume.size}
`;
}

export function ingress(s) {
  const i = s.ingress;
  const notes = [`cert-manager.io/cluster-issuer: letsencrypt`];
  if (i.websocket) notes.push(`nginx.ingress.kubernetes.io/proxy-read-timeout: "3600"`, `nginx.ingress.kubernetes.io/proxy-send-timeout: "3600"`);
  if (i.bodySize) notes.push(`nginx.ingress.kubernetes.io/proxy-body-size: "${i.bodySize}"`);
  return `# Generated by tools/gen-infra.mjs from tools/infra.json. Do not edit by hand. Change the host in your overlay.
apiVersion: networking.k8s.io/v1
kind: Ingress
metadata:
  name: ${s.name}
  annotations:
${notes.map(n => `    ${n}`).join("\n")}
spec:
  ingressClassName: nginx
${i.tls ? `  tls:\n    - hosts: [${i.host}]\n      secretName: ${i.host.replaceAll(".", "-")}-tls\n` : ""}  rules:
    - host: ${i.host}
      http:
        paths:
          - path: ${i.path}
            pathType: Prefix
            backend:
              service:
                name: ${s.name}
                port: { name: http }
`;
}

/** Every file of one part: name → text. */
export function files(s) {
  const out = { "deployment.yaml": deployment(s) };
  if (!s.noService) out["service.yaml"] = service(s);
  if (scales(s)) out["hpa.yaml"] = hpa(s);
  if (s.replicas.min > 1) out["pdb.yaml"] = pdb(s);
  if (s.volume) out["pvc.yaml"] = pvc(s);
  if (s.ingress) out["ingress.yaml"] = ingress(s);
  out["kustomization.yaml"] = `apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
${Object.keys(out).map(f => `  - ${f}`).join("\n")}
`;
  return out;
}

export function everything(config) {
  const all = {};
  for (const s of config.services) for (const [f, text] of Object.entries(files(s))) all[`${s.name}/${f}`] = text;
  all["namespace.yaml"] = `apiVersion: v1\nkind: Namespace\nmetadata:\n  name: ${config.namespace}\n`;
  all["kustomization.yaml"] = `# Generated by tools/gen-infra.mjs from tools/infra.json. Do not edit by hand.
# Everything:  kubectl apply -k infra/k8s      One part:  kubectl apply -k infra/k8s/auth   (with -n ${config.namespace})
# Set each image's registry and version in the images list before applying.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
namespace: ${config.namespace}
resources:
  - namespace.yaml
${config.services.map(s => `  - ${s.name}`).join("\n")}
images:
${config.services.map(s => `  - name: ${s.image}\n    newName: ${config.registry}/${s.image}\n    newTag: latest   # pin a version in production`).join("\n")}
`;
  return all;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const config = JSON.parse(readFileSync(join(here, "infra.json"), "utf8"));
  const out = join(here, "..", "infra", "k8s");
  let stale = 0;
  for (const [path, text] of Object.entries(everything(config))) {
    const file = join(out, path);
    if (process.argv.includes("--check")) {
      if (!existsSync(file) || readFileSync(file, "utf8") !== text) {
        console.error(`out of date: infra/k8s/${path}`);
        stale++;
      }
      continue;
    }
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
  if (stale) process.exit(1);
  if (!process.argv.includes("--check")) console.log("wrote infra/k8s/");
}
